<?php

namespace App\Filament\Resources\HousekeepingAreas\Schemas;

use App\Forms\Components\LeafletMap;
use App\Models\Company;
use App\Models\User;
use App\Support\Code;
use App\Support\Geo;
use Filament\Forms\Components\Hidden;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Components\Utilities\Get;
use Filament\Schemas\Components\Utilities\Set;
use Filament\Schemas\Schema;

class HousekeepingAreaForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make('Area Information')
                    ->columnSpanFull()
                    ->schema([
                        Select::make('company_id')
                            ->label('Company')
                            ->options(Company::pluck('name', 'id'))
                            ->required()
                            ->placeholder('Select company'),
                        Select::make('supervisor_id')
                            ->label('Penanggung Jawab')
                            ->options(fn (): array => User::query()
                                ->whereHas('roles', fn ($query) => $query->where('name', 'patra-jasa'))
                                ->orderBy('name')
                                ->pluck('name', 'id')
                                ->all())
                            ->searchable()
                            ->nullable()
                            ->placeholder('Select supervisor'),
                        TextInput::make('name')
                            ->label('Name')
                            ->required()
                            ->placeholder('e.g., Area Parkir, Taman Kantor')
                            ->live(onBlur: true)
                            ->afterStateUpdated(function (?string $state, ?string $old, Set $set, Get $get): void {
                                if (Code::isAutoGenerated($get('code'), $old)) {
                                    $set('code', Code::fromName($state));
                                }
                            }),
                        TextInput::make('code')
                            ->label('Code')
                            ->unique(
                                ignoreRecord: true,
                                modifyRuleUsing: fn ($rule, Get $get) => $rule->where('company_id', $get('company_id')),
                            )
                            ->placeholder('e.g., area-parkir, taman-kantor')
                            ->helperText('Terisi otomatis dari Name. Bisa diubah manual bila perlu.'),
                        Textarea::make('description')
                            ->label('Description')
                            ->nullable()
                            ->placeholder('Enter area description...'),
                        Toggle::make('is_active')
                            ->label('Active')
                            ->default(true),
                    ])
                    ->columns(2),

                Section::make('Boundary & Size')
                    ->description('Gambar polygon pada peta untuk menentukan batas area housekeeping. Luas dihitung otomatis.')
                    ->columnSpanFull()
                    ->schema([
                        LeafletMap::make('polygon')
                            ->label('Area Boundary')
                            ->mode('polygon')
                            ->height(450)
                            ->columnSpanFull()
                            ->live()
                            ->afterStateHydrated(function (LeafletMap $component, $record): void {
                                if (is_array($record?->polygon) && $record->polygon !== []) {
                                    $component->state($record->polygon);
                                }
                            })
                            ->afterStateUpdated(function (?array $state, Set $set): void {
                                if (empty($state)) {
                                    $set('area_size', null);
                                    $set('latitude', null);
                                    $set('longitude', null);

                                    return;
                                }

                                $set('area_size', Geo::polygonArea($state));

                                $center = Geo::polygonCenter($state);

                                if ($center) {
                                    $set('latitude', $center['lat']);
                                    $set('longitude', $center['lng']);
                                }
                            }),
                        TextInput::make('area_size')
                            ->label('Area Size (m²)')
                            ->numeric()
                            ->readOnly()
                            ->placeholder('Otomatis dari polygon')
                            ->helperText('Luas dihitung otomatis dari polygon (meter persegi).'),
                        Hidden::make('latitude'),
                        Hidden::make('longitude'),
                    ])
                    ->columns(2),
            ]);
    }
}
