<?php

namespace App\Filament\Resources\EquipmentTypes\Schemas;

use App\Models\User;
use App\Support\Code;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Components\Utilities\Get;
use Filament\Schemas\Components\Utilities\Set;
use Filament\Schemas\Schema;

class EquipmentTypeForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make('Equipment Type Information')
                    ->columnSpanFull()
                    ->schema([
                        TextInput::make('name')
                            ->label('Name')
                            ->required()
                            ->placeholder('e.g., Pompa, Storage Tank')
                            ->live(onBlur: true)
                            ->afterStateUpdated(function (?string $state, ?string $old, Set $set, Get $get): void {
                                if (Code::isAutoGenerated($get('code'), $old)) {
                                    $set('code', Code::fromName($state));
                                }
                            }),
                        TextInput::make('code')
                            ->label('Code')
                            ->unique(ignoreRecord: true)
                            ->placeholder('e.g., pompa, storage-tank')
                            ->helperText('Terisi otomatis dari Name. Bisa diubah manual bila perlu.'),
                        Select::make('responsible_user_id')
                            ->label('Penanggung Jawab')
                            ->options(fn (): array => User::technicianCoordinatorOptions())
                            ->searchable()
                            ->nullable()
                            ->helperText('Dipakai sebagai penanggung jawab WO saat generate untuk equipment bertipe ini.'),
                        Textarea::make('description')
                            ->label('Description')
                            ->nullable()
                            ->placeholder('Enter equipment type description...'),
                        Toggle::make('status')
                            ->label('Active')
                            ->default(true),
                    ])
                    ->columns(2),
            ]);
    }
}
