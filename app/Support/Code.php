<?php

namespace App\Support;

use Illuminate\Support\Str;

class Code
{
    /**
     * Ubah nama menjadi kode yang ramah URL/dokumen.
     *
     * Contoh: "Pompa" -> "pompa", "Storage Tank" -> "storage-tank".
     */
    public static function fromName(?string $name): string
    {
        return Str::slug((string) $name);
    }

    /**
     * Apakah nilai kode saat ini masih "bawaan" dari nama sebelumnya,
     * sehingga aman untuk ditimpa otomatis saat nama berubah.
     */
    public static function isAutoGenerated(?string $currentCode, ?string $previousName): bool
    {
        $currentCode = (string) $currentCode;

        if ($currentCode === '') {
            return true;
        }

        return $currentCode === static::fromName($previousName);
    }
}
