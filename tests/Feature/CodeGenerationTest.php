<?php

namespace Tests\Feature;

use App\Filament\Resources\Areas\Pages\CreateArea;
use App\Filament\Resources\EquipmentTypes\Pages\CreateEquipmentType;
use App\Filament\Resources\EquipmentTypes\Pages\EditEquipmentType;
use App\Models\Area;
use App\Models\Company;
use App\Models\EquipmentType;
use App\Models\User;
use App\Support\Code;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Gate;
use Livewire\Livewire;
use Tests\TestCase;

class CodeGenerationTest extends TestCase
{
    use RefreshDatabase;

    protected User $user;

    protected Company $company;

    protected function setUp(): void
    {
        parent::setUp();

        config(['app.env' => 'local']);
        Gate::before(fn (): bool => true);

        $this->user = User::factory()->create();
        $this->company = Company::create(['code' => 'CO', 'name' => 'Demo Company']);
    }

    public function test_from_name_creates_lowercase_slug(): void
    {
        $this->assertSame('pompa', Code::fromName('Pompa'));
        $this->assertSame('storage-tank', Code::fromName('Storage Tank'));
        $this->assertSame('gate-valve-gv', Code::fromName('Gate Valve (GV)'));
        $this->assertSame('', Code::fromName(null));
    }

    public function test_is_auto_generated_only_when_blank_or_matches_previous_name(): void
    {
        $this->assertTrue(Code::isAutoGenerated('', 'Pompa'));
        $this->assertTrue(Code::isAutoGenerated('pompa', 'Pompa'));
        $this->assertFalse(Code::isAutoGenerated('PMP', 'Pompa'));
        $this->assertFalse(Code::isAutoGenerated('pompa-lama', 'Pompa Baru'));
    }

    public function test_equipment_type_code_follows_name_while_typing(): void
    {
        $this->actingAs($this->user);

        Livewire::test(CreateEquipmentType::class)
            ->fillForm(['name' => 'Pompa'])
            ->assertSchemaStateSet(['code' => 'pompa'])
            ->fillForm(['name' => 'Storage Tank'])
            ->assertSchemaStateSet(['code' => 'storage-tank']);
    }

    public function test_equipment_type_keeps_manually_edited_code(): void
    {
        $this->actingAs($this->user);

        Livewire::test(CreateEquipmentType::class)
            ->fillForm([
                'name' => 'Pompa',
                'code' => 'PMP',
            ])
            ->fillForm(['name' => 'Pompa Sentrifugal'])
            ->assertSchemaStateSet(['code' => 'PMP']);
    }

    public function test_equipment_type_code_is_generated_on_create_when_blank(): void
    {
        $this->actingAs($this->user);

        Livewire::test(CreateEquipmentType::class)
            ->fillForm([
                'name' => 'Pompa',
                'code' => '',
                'status' => true,
            ])
            ->call('create')
            ->assertHasNoFormErrors();

        $this->assertDatabaseHas('equipment_types', [
            'name' => 'Pompa',
            'code' => 'pompa',
        ]);
    }

    public function test_area_code_follows_name_while_typing(): void
    {
        $this->actingAs($this->user);

        Livewire::test(CreateArea::class)
            ->fillForm([
                'company_id' => $this->company->id,
                'name' => 'Pump Loading',
            ])
            ->assertSchemaStateSet(['code' => 'pump-loading']);
    }

    public function test_area_code_is_generated_on_create_when_blank(): void
    {
        $this->actingAs($this->user);

        Livewire::test(CreateArea::class)
            ->fillForm([
                'company_id' => $this->company->id,
                'name' => 'Loading',
                'code' => '',
            ])
            ->call('create')
            ->assertHasNoFormErrors();

        $this->assertDatabaseHas('areas', [
            'company_id' => $this->company->id,
            'name' => 'Loading',
            'code' => 'loading',
        ]);
    }

    public function test_area_code_must_be_unique_per_company(): void
    {
        $otherCompany = Company::create(['code' => 'CO2', 'name' => 'Other Company']);

        Area::create([
            'company_id' => $this->company->id,
            'code' => 'loading',
            'name' => 'Loading',
        ]);

        $this->actingAs($this->user);

        Livewire::test(CreateArea::class)
            ->fillForm([
                'company_id' => $this->company->id,
                'name' => 'Loading',
            ])
            ->call('create')
            ->assertHasFormErrors(['code']);

        Livewire::test(CreateArea::class)
            ->fillForm([
                'company_id' => $otherCompany->id,
                'name' => 'Loading',
            ])
            ->call('create')
            ->assertHasNoFormErrors();

        $this->assertSame(2, Area::where('code', 'loading')->count());
    }

    public function test_edit_pages_render_with_auto_code_fields(): void
    {
        $type = EquipmentType::create(['code' => 'pompa', 'name' => 'Pompa']);
        $area = Area::create([
            'company_id' => $this->company->id,
            'code' => 'loading',
            'name' => 'Loading',
        ]);

        $this->actingAs($this->user)
            ->get("/admin/equipment-types/{$type->id}/edit")
            ->assertSuccessful();

        $this->actingAs($this->user)
            ->get("/admin/areas/{$area->id}/edit")
            ->assertSuccessful();
    }

    public function test_edit_page_regenerates_code_when_cleared(): void
    {
        $type = EquipmentType::create(['code' => 'lama', 'name' => 'Pompa']);

        $this->actingAs($this->user);

        Livewire::test(EditEquipmentType::class, [
            'record' => $type->getRouteKey(),
        ])
            ->fillForm([
                'name' => 'Pompa Sentrifugal',
                'code' => '',
            ])
            ->call('save')
            ->assertHasNoFormErrors();

        $this->assertSame('pompa-sentrifugal', $type->fresh()->code);
    }

    public function test_equipment_type_code_is_unique(): void
    {
        EquipmentType::create(['code' => 'pompa', 'name' => 'Pompa']);

        $this->actingAs($this->user);

        Livewire::test(CreateEquipmentType::class)
            ->fillForm([
                'name' => 'Pompa',
                'status' => true,
            ])
            ->call('create')
            ->assertHasFormErrors(['code']);
    }
}
